package hysteria2

import (
	"bufio"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// A rig with a ULA LAN on its own link beside a GCE uplink and the hy2 TUN, and a home
// LAN with a public /64, a gateway on fe80 and a WireGuard tunnel.
func TestParseLocalBypassV6(t *testing.T) {
	t.Parallel()

	rig := "" +
		"fd000ddd000000000000000000000000 40 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001     eth2\n" +
		"20010000000000000000fffffffffff0 7e 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001 dvpn-hy2-client\n" +
		"fe800000000000000000000000000000 40 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001     ens4\n" +
		"00000000000000000000000000000000 00 00000000000000000000000000000000 00 00000000000000000000000000000000 00000400 00000001 00000000 00000001 dvpn-hy2-client\n" +
		"00000000000000000000000000000001 80 00000000000000000000000000000000 00 00000000000000000000000000000000 00000000 00000001 00000000 00200001       lo\n" +
		"ff000000000000000000000000000000 08 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001     ens4\n"
	require.Equal(t, []string{"fe80::/10", "fd00:ddd::/64"},
		parseLocalBypassV6(bufio.NewScanner(strings.NewReader(rig)), "dvpn-hy2-client"))

	home := "" +
		"2001db80001000000000000000000000 40 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001   wlp2s0\n" +
		"00000000000000000000000000000000 00 00000000000000000000000000000000 00 fe800000000000000000000000000001 00000400 00000001 00000000 00000003   wlp2s0\n" +
		"00000000000000000000000000000000 00 00000000000000000000000000000000 00 2001db80001000000000000000000001 00000500 00000001 00000000 00000003     eth1\n" +
		"fd420000000000000000000000000000 40 00000000000000000000000000000000 00 00000000000000000000000000000000 00000100 00000001 00000000 00000001      wg0\n"
	require.Equal(t, []string{"fe80::/10", "2001:db80:10::/64", "2001:db80:10::1/128"},
		parseLocalBypassV6(bufio.NewScanner(strings.NewReader(home)), ""))
}
